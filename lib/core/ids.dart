/// 生成进程内唯一的 id。
///
/// ## 为什么不能只用时间戳
///
/// 全项目原来都是 `DateTime.now().microsecondsSinceEpoch.toString()`。
/// 看起来精度绰绰有余，但 `DateTime.now()` 的**实际分辨率取决于操作系统**：
/// Windows 上通常是毫秒级（粗到一次 tick 内的多次调用返回完全相同的值），
/// Android 上也可能受时钟源限制。于是"连续快速创建两个对象"会拿到**同一个 id**。
///
/// 后果不是"id 不好看"，而是**误删**：删除是按 id 匹配的
/// （`removeWhere((x) => x.id == id)`），两条同 id 的记录会被一次删光，
/// 用户看到的是"我只删了一条，怎么少了两条"。
///
/// 这个 bug 是 `test/memory_test.dart` 抓出来的：连续 add 三条、
/// forget 一条，结果三条全没了。
///
/// ## 修法
///
/// 时间戳 + **进程内单调递增的序号**：
/// · 时间戳保证跨进程、跨重启不会撞
/// · 序号保证同一进程内**必不撞**，不受系统时钟分辨率影响
///
/// 序号不持久化也没关系：跨进程靠时间戳就够（两个进程在同一微秒创建对象
/// 的概率可以忽略）。
String newId() => '${DateTime.now().microsecondsSinceEpoch}_${_seq++}';

int _seq = 0;
